-- Regenerates lua/google-translate/languages.lua from the languages Google Translate lists.
-- Usage: nvim -l scripts/gen_languages.lua

local URL = "https://translate.googleapis.com/translate_a/l?client=gtx&hl=en"
local OUTPUT = "lua/google-translate/languages.lua"

local cmd = { "curl", "--silent", "--show-error", "--fail", URL }
local result = vim.system(cmd, { text = true }):wait()
if result.code ~= 0 then
  io.stderr:write(result.stderr)
  os.exit(1)
end

local response = vim.json.decode(result.stdout)

---@param names table<string, string> language code to display name
---@param exclude string[]
---@return string[]
local function entries(names, exclude)
  local codes = vim.tbl_filter(function(code)
    return not vim.list_contains(exclude, code)
  end, vim.tbl_keys(names))
  table.sort(codes)
  return vim.tbl_map(function(code)
    return string.format("    %q, -- %s", code, names[code])
  end, codes)
end

local lines = {
  "-- Generated by scripts/gen_languages.lua. Do not edit by hand.",
  "return {",
  "  source = {",
}
vim.list_extend(lines, entries(response.sl, {}))
vim.list_extend(lines, { "  },", "  target = {" })
vim.list_extend(lines, entries(response.tl, { "auto" }))
vim.list_extend(lines, { "  },", "}", "" })

local file = assert(io.open(OUTPUT, "w"))
file:write(table.concat(lines, "\n"))
file:close()
print(string.format("wrote %s", OUTPUT))
